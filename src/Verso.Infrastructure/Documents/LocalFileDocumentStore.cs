using System.Text.RegularExpressions;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Options;
using Verso.Application.Documents;

namespace Verso.Infrastructure.Documents;

public sealed class DocumentStoreOptions
{
    public const string Section = "Documents";

    /// <summary>
    /// Root folder of the local document store. Default: <c>%LOCALAPPDATA%\Verso\documents</c> (development).
    /// On servers, set it to a folder only the Worker's service account can write.
    /// </summary>
    public string? RootPath { get; set; }
}

/// <summary>
/// MVP <see cref="IDocumentStore"/>: files under a root folder. Keys are generated by Verso and checked against a
/// strict pattern, and the resolved path must stay inside the root. Writes go to a temporary file first and are
/// then moved into place, so a crash never leaves a half-written document under its key.
/// </summary>
internal sealed partial class LocalFileDocumentStore : IDocumentStore
{
    public const string ProviderName = "local-fs";

    private readonly string _root;

    public LocalFileDocumentStore(IOptions<DocumentStoreOptions> options)
    {
        var configured = options.Value.RootPath;
        _root = Path.GetFullPath(string.IsNullOrWhiteSpace(configured)
            ? Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Verso", "documents")
            : configured);
    }

    public string Provider => ProviderName;

    public string RootPath => _root;

    [GeneratedRegex(@"^[a-z]+(/[A-Za-z0-9_\-]+)*/[A-Za-z0-9_\-]+\.[a-z]{1,8}$")]
    private static partial Regex KeyPattern();

    public async Task WriteAsync(string key, byte[] content, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(content);
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temp = $"{path}.{Guid.NewGuid():N}.tmp";
        try
        {
            await using (var stream = new FileStream(temp, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, FileOptions.Asynchronous | FileOptions.WriteThrough))
            {
                await stream.WriteAsync(content, ct);
            }

            File.Move(temp, path, overwrite: true);
        }
        finally
        {
            if (File.Exists(temp))
            {
                File.Delete(temp);
            }
        }
    }

    public async Task<byte[]?> ReadAsync(string key, CancellationToken ct)
    {
        var path = Resolve(key);
        try
        {
            return await File.ReadAllBytesAsync(path, ct);
        }
        catch (Exception ex) when (ex is FileNotFoundException or DirectoryNotFoundException)
        {
            return null;
        }
    }

    public Task DeleteAsync(string key, CancellationToken ct)
    {
        File.Delete(Resolve(key)); // no error when missing
        return Task.CompletedTask;
    }

    private string Resolve(string key)
    {
        if (key.Length > 300 || !KeyPattern().IsMatch(key))
        {
            throw new ArgumentException($"Invalid storage key '{key}'.", nameof(key));
        }

        var path = Path.GetFullPath(Path.Combine(_root, key.Replace('/', Path.DirectorySeparatorChar)));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
        {
            throw new ArgumentException($"Storage key '{key}' leaves the document root.", nameof(key));
        }

        return path;
    }
}

public static class DocumentStoreRegistration
{
    /// <summary>
    /// The Worker writes documents; the API only reads them (downloads, M8), and both use the same
    /// <c>Documents:RootPath</c>. The API never calls <see cref="IDocumentStore.WriteAsync"/>.
    /// </summary>
    public static IServiceCollection AddVersoDocumentStore(this IServiceCollection services, IConfiguration configuration)
    {
        var options = new DocumentStoreOptions { RootPath = configuration[$"{DocumentStoreOptions.Section}:{nameof(DocumentStoreOptions.RootPath)}"] };
        services.AddSingleton<IDocumentStore>(new LocalFileDocumentStore(Options.Create(options)));
        return services;
    }
}
